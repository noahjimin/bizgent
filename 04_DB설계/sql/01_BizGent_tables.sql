/* ---------- 1. 회원·요금제 ---------- */

CREATE TABLE MEMBERS (
    MEMBER_ID           NUMBER(10)      NOT NULL,
    EMAIL               VARCHAR2(100)   NOT NULL,
    PASSWORD            VARCHAR2(255)   NOT NULL,
    MEMBER_NAME         VARCHAR2(50)    NOT NULL,
    PHONE               VARCHAR2(20)    NULL,
    TERMS_AGREED_YN     CHAR(1)         DEFAULT 'N' NOT NULL,
    TERMS_AGREED_AT     DATE            DEFAULT SYSDATE NOT NULL,
    MEMBER_STATUS       VARCHAR2(20)    DEFAULT 'ACTIVE' NOT NULL,
    JOINED_AT           DATE            DEFAULT SYSDATE NOT NULL,
    WITHDRAWN_AT        DATE            NULL,
    CONSTRAINT PK_MEMBERS PRIMARY KEY (MEMBER_ID),
    CONSTRAINT UK_MEMBERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_MEMBERS_1 CHECK (TERMS_AGREED_YN IN ('Y', 'N')),
    CONSTRAINT CK_MEMBERS_2 CHECK (MEMBER_STATUS IN ('ACTIVE', 'WITHDRAWN'))
);

CREATE TABLE PRICE_PLAN (
    PLAN_CODE               VARCHAR2(20)    NOT NULL,
    PLAN_NAME               VARCHAR2(50)    NOT NULL,
    MONTHLY_PRICE           NUMBER(10)      NOT NULL,
    MONTHLY_CAMPAIGN_LIMIT  NUMBER(5)       NOT NULL,
    MAX_CHANNEL_COUNT       NUMBER(2)       NOT NULL,
    MONTHLY_IMAGE_LIMIT     NUMBER(3)       NOT NULL,
    CONSTRAINT PK_PRICE_PLAN PRIMARY KEY (PLAN_CODE)
);

CREATE TABLE SUBSCRIPTION (
    SUBSCRIPTION_ID     NUMBER(10)      NOT NULL,
    MEMBER_ID           NUMBER(10)      NOT NULL,
    PLAN_CODE           VARCHAR2(20)    NOT NULL,
    START_DATE          DATE            NOT NULL,
    END_DATE            DATE            NULL,
    SUBSCRIPTION_STATUS VARCHAR2(20)    NOT NULL,
    PAYMENT_STATUS      VARCHAR2(20)    NOT NULL,
    CREATED_AT          DATE            DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_SUBSCRIPTION PRIMARY KEY (SUBSCRIPTION_ID),
    CONSTRAINT CK_SUBSCRIPTION_1 CHECK (SUBSCRIPTION_STATUS IN ('ACTIVE', 'CANCELED', 'EXPIRED'))
